// Core design schema. Pure data — no framework imports. Everything in /src/engine
// operates on these types so it can run in a Web Worker, in tests, or on a server.

export type ComponentType =
  | 'client'
  | 'loadBalancer'
  | 'appServer'
  | 'cache'
  | 'sqlDb'
  | 'queue'
  | 'worker'
  | 'cdn';

export const COMPONENT_TYPES: ComponentType[] = [
  'client',
  'loadBalancer',
  'appServer',
  'cache',
  'sqlDb',
  'queue',
  'worker',
  'cdn',
];

export interface NodeParams {
  /** Requests per second ONE instance can serve. */
  capacity: number;
  /** Fixed per-hop latency in ms (network + baseline processing), added on top of queueing/service time. */
  latencyMs: number;
  /** Number of identical instances behind this node (modeled as an M/M/c pool). */
  instances: number;
  /** Cache / CDN: probability a read is served without going further (0..1). */
  hitRate?: number;
  /** SQL DB: number of read replicas (each with `capacity`). Writes only go to primaries. */
  replicas?: number;
  /** Message queue: max messages/s delivered to consumers (workers). */
  consumerRate?: number;
  /** Max requests waiting in this node's queue before new arrivals are dropped. Defaults to ~1s of work. */
  maxQueue?: number;
}

export interface DesignNode {
  id: string;
  type: ComponentType;
  label: string;
  position: { x: number; y: number };
  params: NodeParams;
}

export interface DesignEdge {
  id: string;
  source: string;
  target: string;
}

export interface Workload {
  /** Total requests per second generated by all clients (split evenly between client nodes). */
  rps: number;
  /** Fraction of requests that are reads (0..1). */
  readRatio: number;
  /** Average response/object size in KB (used by the linter for CDN advice). */
  objectSizeKb: number;
}

export interface Design {
  version: 1;
  name: string;
  nodes: DesignNode[];
  edges: DesignEdge[];
  workload: Workload;
}

export type Op = 'read' | 'write';
